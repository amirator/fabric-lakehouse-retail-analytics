"""One command: python run.py  ->  data check, bronze/silver/gold notebooks on DuckDB, gold JSON, README, screenshots."""
import json, subprocess, sys
from decimal import Decimal
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parent
NOTEBOOKS = ["nb_01_bronze_ingest", "nb_02_silver_conform", "nb_03_gold_star_schema"]
DB = ROOT / "data" / "lakehouse.duckdb"
GOLD_EXPORTS = ["gold_monthly_kpis", "gold_category_kpis", "gold_state_kpis", "gold_review_by_lateness"]


def run_notebooks(con):
    for nb in NOTEBOOKS:
        src = (ROOT / "fabric" / f"{nb}.Notebook" / "notebook-content.py").read_text()
        print(f"--- {nb}")
        exec(compile(src, nb, "exec"), {"con": con, "RAW_DIR": str(ROOT / "data" / "raw")})


def rows(con, sql):
    cur = con.execute(sql)
    cols = [c[0] for c in cur.description]
    conv = lambda v: float(v) if isinstance(v, Decimal) else v
    return [{c: conv(v) for c, v in zip(cols, r)} for r in cur.fetchall()]


def headline(con):
    k = rows(con, """
      SELECT COUNT(*) AS orders, SUM(is_delivered) AS delivered_orders,
             ROUND(SUM(CASE WHEN is_delivered=1 THEN items_value END), 2) AS gmv,
             ROUND(SUM(CASE WHEN is_delivered=1 THEN items_value END) / SUM(is_delivered), 2) AS aov,
             ROUND(AVG(CASE WHEN is_delivered=1 THEN is_late END) * 100, 2) AS late_pct,
             ROUND(AVG(CASE WHEN is_delivered=1 THEN delivery_days END), 2) AS avg_delivery_days,
             ROUND(AVG(CASE WHEN is_delivered=1 THEN review_score END), 3) AS avg_review,
             CAST(MIN(order_date) AS VARCHAR) AS first_date, CAST(MAX(order_date) AS VARCHAR) AS last_date
      FROM fact_orders""")[0]
    lat = {r["delivery"]: r for r in rows(con, "SELECT * FROM gold_review_by_lateness")}
    k["review_on_time"], k["review_late"] = lat["on_time"]["avg_review"], lat["late"]["avg_review"]
    k["low_review_on_time_pct"], k["low_review_late_pct"] = lat["on_time"]["low_review_pct"], lat["late"]["low_review_pct"]
    top = rows(con, "SELECT category, gmv FROM gold_category_kpis LIMIT 1")[0]
    k["top_category"], k["top_category_gmv"] = top["category"], top["gmv"]
    sp = rows(con, "SELECT gmv FROM gold_state_kpis WHERE state='SP'")[0]["gmv"]
    k["sp_gmv_share_pct"] = round(sp / k["gmv"] * 100, 2)
    k["table_counts"] = {t: con.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0] for (t,) in
                         con.execute("SELECT table_name FROM information_schema.tables ORDER BY table_name").fetchall()}
    return k


def main():
    subprocess.run([sys.executable, str(ROOT / "scripts" / "download_data.py")], check=True)
    DB.unlink(missing_ok=True)
    con = duckdb.connect(str(DB))
    run_notebooks(con)
    gold = {t: rows(con, f"SELECT * FROM {t}") for t in GOLD_EXPORTS}
    kpis = headline(con)
    gold["headline"] = {k: v for k, v in kpis.items() if k != "table_counts"}
    out = ROOT / "web" / "data"
    out.mkdir(parents=True, exist_ok=True)
    (out / "gold.json").write_text(json.dumps(gold, indent=1) + "\n")
    (out / "gold.js").write_text("// generated by run.py; lets index.html work from file://\nwindow.GOLD = " + json.dumps(gold) + ";\n")
    (ROOT / "kpis.json").write_text(json.dumps(kpis, indent=2) + "\n")
    con.close()
    subprocess.run([sys.executable, str(ROOT / "scripts" / "build_tmdl.py")], check=True)
    subprocess.run([sys.executable, str(ROOT / "scripts" / "build_readme.py")], check=True)
    if "--no-screenshots" not in sys.argv:
        subprocess.run([sys.executable, str(ROOT / "scripts" / "screenshots.py")], check=True)
    print(json.dumps(gold["headline"], indent=2))


if __name__ == "__main__":
    main()
